import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";

// REAL-POSTGRES checks for migration 0119 (collection closure episodes) on an
// in-memory PGlite database built from db/schema.ts plus the migration's own SQL
// — the same convention as the 0115 / 0117 tests. No shared or production
// database can be reached; nothing here applies 0119 anywhere else.
import * as schema from "@/db/schema";
import { createTestDb } from "./_pglite";

const SQL = readFileSync(resolve(__dirname, "../../db/migrations/0119_collection_closures.sql"), "utf8");
const BASE = {
  employees: schema.employees,
  customerMasters: schema.customerMasters,
  collectionMasterImports: schema.collectionMasterImports,
  collectionMasterCompanies: schema.collectionMasterCompanies,
};

let pg: Awaited<ReturnType<typeof createTestDb>>["pg"];
let alpha = "";
let beta = "";
let emp = "";

beforeAll(async () => {
  const made = await createTestDb(BASE);
  pg = made.pg;
  // Supabase grants every new table to its REST roles by default; the migration must take that away.
  await pg.exec(`create role anon nologin; create role authenticated nologin;
    alter default privileges in schema public grant all on tables to anon, authenticated;`);
  await pg.exec(SQL);
  emp = (await pg.query<{ id: string }>(`insert into employees (name, email, role) values ('Asha', 'asha@example.test', 'both') returning id`)).rows[0]!.id;
  const co = async (name: string) =>
    (await pg.query<{ id: string }>(`insert into collection_master_companies (company_name, name_key) values ($1, $2) returning id`, [name, name.toLowerCase().replace(/[^a-z0-9]/g, "")])).rows[0]!.id;
  alpha = await co("Alpha Traders");
  beta = await co("Beta Works");
});
afterAll(async () => {
  await pg?.close();
});

const close = (companyId: string, over: Record<string, unknown> = {}) =>
  pg.query<{ id: string; closed_at: Date }>(
    `insert into collection_closures (company_id, close_reason, close_source_key, close_source_ref, final_outstanding, final_debit, final_credit, as_of_date)
     values ($1, $2, $3, $4, $5, $6, $7, $8) returning id, closed_at`,
    [
      companyId,
      over.reason ?? "outstanding_zero",
      over.sourceKey ?? "test_source",
      over.sourceRef ?? "ref-1",
      over.outstanding ?? "0.00",
      over.debit ?? null,
      over.credit ?? null,
      over.asOf ?? null,
    ],
  );
const reopen = (id: string) =>
  pg.query(`update collection_closures set reopened_at = now(), reopen_reason = 'outstanding_positive', reopen_source_ref = 'ref-2' where id = $1`, [id]);
const code = async (p: Promise<unknown>) => {
  try {
    await p;
    return "ok";
  } catch (err) {
    return (err as { code?: string }).code ?? (err as Error).message;
  }
};

describe("migration 0119 — structure and security", () => {
  it("is idempotent: applying it twice changes nothing and raises nothing", async () => {
    await pg.exec(SQL);
  });

  it("adds no data: the new table starts empty and no other table is touched", async () => {
    expect((await pg.query(`select 1 from collection_closures`)).rows).toHaveLength(0);
    const stmts = SQL.replace(/--[^\n]*/g, ""); // the statements, not the explanatory comments
    expect(stmts).not.toMatch(/\bINSERT\s+INTO\b|\bUPDATE\s+\S+\s+SET\b|\bDELETE\s+FROM\b|\bTRUNCATE\b|\bCOPY\b/i);
    expect(stmts).not.toMatch(/\bGRANT\b/i);
    expect(stmts).not.toMatch(/\bCREATE\s+POLICY\b/i);
    expect(stmts).not.toMatch(/\bDROP\b/i);
  });

  it("RLS is on, with no policies", async () => {
    const r = await pg.query<{ rls: boolean }>(`select relrowsecurity as rls from pg_class where relname = 'collection_closures'`);
    expect(r.rows).toEqual([{ rls: true }]);
    expect((await pg.query(`select 1 from pg_policies where tablename = 'collection_closures'`)).rows).toHaveLength(0);
  });

  it("the REST roles hold no privilege on it, despite the default grant", async () => {
    const r = await pg.query<{ grantee: string }>(
      `select grantee from information_schema.role_table_grants where table_name = 'collection_closures' and grantee in ('anon', 'authenticated')`,
    );
    expect(r.rows).toEqual([]);
  });

  it("closed_at is generated by the database", async () => {
    const before = Date.now();
    const { rows } = await close(alpha);
    expect(rows[0]!.closed_at).toBeInstanceOf(Date);
    expect(Math.abs(rows[0]!.closed_at.getTime() - before)).toBeLessThan(60_000);
    await pg.query(`update collection_closures set reopened_at = closed_at, reopen_reason = 'outstanding_positive' where id = $1`, [rows[0]!.id]);
  });

  it("keeps money exact (numeric, never a float)", async () => {
    const { rows } = await close(beta, { debit: "125000.50", credit: "125000.50", asOf: "2026-10-27" });
    const r = await pg.query<{ final_outstanding: string; final_debit: string; final_credit: string; as_of_date: string }>(
      `select final_outstanding::text, final_debit::text, final_credit::text, as_of_date::text from collection_closures where id = $1`,
      [rows[0]!.id],
    );
    expect(r.rows[0]).toEqual({ final_outstanding: "0.00", final_debit: "125000.50", final_credit: "125000.50", as_of_date: "2026-10-27" });
    await reopen(rows[0]!.id);
  });
});

describe("migration 0119 — constraints", () => {
  it("allows ONE open closure per company; a reopened one frees the slot and stays in history", async () => {
    const first = (await close(alpha)).rows[0]!.id;
    expect(await code(close(alpha))).toBe("23505"); // a second open closure for the same company
    expect(await code(close(beta))).toBe("ok"); // another company is independent
    await reopen(first);
    expect(await code(close(alpha))).toBe("ok"); // a new episode after reopening
    const n = await pg.query<{ n: number }>(`select count(*)::int as n from collection_closures where company_id = $1`, [alpha]);
    expect(n.rows[0]!.n).toBe(3); // every episode kept
    const open = await pg.query<{ n: number }>(`select count(*)::int as n from collection_closures where company_id = $1 and reopened_at is null`, [alpha]);
    expect(open.rows[0]!.n).toBe(1);
    await pg.exec(`update collection_closures set reopened_at = now(), reopen_reason = 'outstanding_positive' where reopened_at is null`);
  });

  it("the reason is constrained (only outstanding_zero)", async () => {
    expect(await code(close(alpha, { reason: "manual" }))).toBe("23514");
    expect(await code(close(alpha, { reason: "" }))).toBe("23514");
  });

  it("an outstanding_zero closure records exactly zero — no tolerance", async () => {
    expect(await code(close(alpha, { outstanding: "0.01" }))).toBe("23514");
    expect(await code(close(alpha, { outstanding: "-0.01" }))).toBe("23514");
    expect(await code(close(alpha, { outstanding: "125000.00" }))).toBe("23514");
  });

  it("needs a non-blank source key; final_outstanding and company are required", async () => {
    expect(await code(close(alpha, { sourceKey: "   " }))).toBe("23514");
    expect(await code(pg.query(`insert into collection_closures (company_id, close_reason, close_source_key) values ($1, 'outstanding_zero', 's')`, [alpha]))).toBe("23502");
    expect(await code(pg.query(`insert into collection_closures (close_reason, close_source_key, final_outstanding) values ('outstanding_zero', 's', 0)`))).toBe("23502");
  });

  it("the company must exist, and a company with closure history cannot be deleted (RESTRICT)", async () => {
    expect(await code(close("00000000-0000-4000-8000-000000000000"))).toBe("23503");
    expect(await code(pg.query(`delete from collection_master_companies where id = $1`, [alpha]))).toBe("23503");
    const fk = await pg.query<{ col: string; del: string }>(
      `select a.attname as col, c.confdeltype as del from pg_constraint c join pg_attribute a on a.attrelid = c.conrelid and a.attnum = c.conkey[1]
       where c.conrelid = 'collection_closures'::regclass and c.contype = 'f' order by a.attname`,
    );
    // r = RESTRICT (the company), n = SET NULL (the actors)
    expect(fk.rows).toEqual([
      { col: "closed_by_id", del: "n" },
      { col: "company_id", del: "r" },
      { col: "reopened_by_id", del: "n" },
    ]);
  });

  it("an open closure carries no reopening fields; a reopened one needs when and why, not before the closure", async () => {
    const id = (await close(alpha)).rows[0]!.id;
    expect(await code(pg.query(`update collection_closures set reopen_reason = 'outstanding_positive' where id = $1`, [id]))).toBe("23514");
    expect(await code(pg.query(`update collection_closures set reopen_source_ref = 'x' where id = $1`, [id]))).toBe("23514");
    expect(await code(pg.query(`update collection_closures set reopened_by_id = $2 where id = $1`, [id, emp]))).toBe("23514");
    expect(await code(pg.query(`update collection_closures set reopened_at = now() where id = $1`, [id]))).toBe("23514");
    expect(await code(pg.query(`update collection_closures set reopened_at = now(), reopen_reason = 'other' where id = $1`, [id]))).toBe("23514");
    expect(await code(pg.query(`update collection_closures set reopened_at = closed_at - interval '1 second', reopen_reason = 'outstanding_positive' where id = $1`, [id]))).toBe("23514");
    expect(await code(pg.query(`update collection_closures set reopened_at = now(), reopen_reason = 'outstanding_positive', reopened_by_id = $2 where id = $1`, [id, emp]))).toBe("ok");
  });

  it("deleting an employee clears the actor, keeping the closure", async () => {
    const other = (await pg.query<{ id: string }>(`insert into employees (name, email, role) values ('Temp', 'temp@example.test', 'both') returning id`)).rows[0]!.id;
    const id = (await pg.query<{ id: string }>(
      `insert into collection_closures (company_id, close_reason, close_source_key, final_outstanding, closed_by_id) values ($1, 'outstanding_zero', 's', 0, $2) returning id`,
      [beta, other],
    )).rows[0]!.id;
    await pg.query(`delete from employees where id = $1`, [other]);
    const r = await pg.query<{ closed_by_id: string | null }>(`select closed_by_id from collection_closures where id = $1`, [id]);
    expect(r.rows).toEqual([{ closed_by_id: null }]);
    await reopen(id);
  });
});

describe("db/schema.ts matches migration 0119", () => {
  it("same columns, constraints and indexes as the schema the app compiles against", async () => {
    const fromSchema = await createTestDb({ ...BASE, collectionClosures: schema.collectionClosures });
    const describeDb = async (db: typeof pg) => ({
      columns: (await db.query(
        `select column_name, data_type, is_nullable, column_default, numeric_precision, numeric_scale from information_schema.columns where table_name = 'collection_closures' order by column_name`,
      )).rows,
      checks: (await db.query(`select conname, contype from pg_constraint where conrelid = 'collection_closures'::regclass order by conname`)).rows,
      indexes: (await db.query<{ indexname: string; indexdef: string }>(`select indexname, indexdef from pg_indexes where tablename = 'collection_closures' order by indexname`)).rows,
    });
    try {
      const a = await describeDb(pg);
      const b = await describeDb(fromSchema.pg);
      expect(b.columns).toEqual(a.columns);
      // Drizzle and hand-written SQL name primary and foreign keys differently; the CHECK and UNIQUE names must match.
      const named = (rows: unknown[]) => (rows as { conname: string; contype: string }[]).filter((r) => r.contype === "c").map((r) => r.conname);
      expect(named(b.checks)).toEqual(named(a.checks));
      expect(named(a.checks)).toEqual([
        "collection_closures_close_reason_check",
        "collection_closures_reopen_check",
        "collection_closures_reopen_reason_check",
        "collection_closures_source_key_check",
        "collection_closures_zero_check",
      ]);
      const norm = (rows: { indexname: string; indexdef: string }[]) =>
        rows.filter((r) => !r.indexname.endsWith("_pkey")).map((r) => ({ name: r.indexname, def: r.indexdef.replace(/\s+/g, " ").replace(/"/g, "").replace(/ USING btree/g, "") }));
      expect(norm(b.indexes)).toEqual(norm(a.indexes));
      expect(norm(a.indexes).find((i) => i.name === "collection_closures_one_open_uq")?.def).toMatch(/UNIQUE INDEX .* \(company_id\) WHERE \(reopened_at IS NULL\)/);
    } finally {
      await fromSchema.pg.close();
    }
  });
});
